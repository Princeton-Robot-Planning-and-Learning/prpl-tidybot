MODEL = (
    Path(kinder.__file__).parent / "envs/dynamic3d/models/stanford_tidybot/tidybot.xml"
)
HOME = [0, 0.248, math.pi, -2.292, -0.01, 0.872, math.pi / 2]
BOUNDS = [[-3, -3], [3, 3]]


@pytest.fixture(scope="module")
def geometry():
    """Use the actual installed public URDF and measured-style arm posture."""
    return build_geometry(MODEL, HOME, 0.05, DEFAULT_NAVIGATION)


def box(center, half):
    """Construct an environmental box, not a replacement robot shape."""
    return {"center": center, "half_size": half}


def test_uses_existing_urdf_collision_meshes_and_base_box(geometry):
    """The scene is the real_sim robot, not geometries manufactured from AABBs."""
    with TransitChecker(geometry, [], BOUNDS) as checker:
        scene = checker.scene
        shapes = [
            data
            for link in range(
                -1, p.getNumJoints(scene.arm.robot_id, physicsClientId=scene.client)
            )
            for data in p.getCollisionShapeData(
                scene.arm.robot_id, link, physicsClientId=scene.client
            )
        ]
        assert any(data[2] == p.GEOM_MESH for data in shapes)
        assert scene.robot.get_name() == "tidybot-kinova"
        assert "parts" not in geometry
        assert scene.robot.base.urdf_path.name == "tidybot_base.urdf"
        assert checker.free([0, 0, 0])


def test_height_separation_uses_mesh_and_still_rejects_true_contact(geometry):
    """A low box below an elevated wrist is free, a box at the wrist is not."""
    with TransitChecker(
        geometry, [box([0.68, 0, 0.1], [0.02, 0.02, 0.1])], BOUNDS
    ) as checker:
        assert checker.free([0, 0, 0])
    with TransitChecker(
        geometry, [box([0.68, 0, 0.8], [0.04, 0.04, 0.04])], BOUNDS
    ) as checker:
        assert not checker.free([0, 0, 0])
    with TransitChecker(
        geometry, [box([0, 0, 0.1], [0.05, 0.05, 0.1])], BOUNDS
    ) as checker:
        assert not checker.free([0, 0, 0])


def test_rotation_checks_intermediate_mesh_sweep(geometry):
    """A wrist-height obstacle intersects a rotation even with clear endpoints."""
    obstacle = box([0.48, 0.48, 0.8], [0.025, 0.025, 0.025])
    with TransitChecker(geometry, [obstacle], BOUNDS) as checker:
        assert checker.free([0, 0, 0]) and checker.free([0, 0, math.pi / 2])
        assert not checker.segment([0, 0, 0], [0, 0, math.pi / 2])


def test_swept_mesh_check_catches_wall_between_translation_endpoints(geometry):
    """Sparse supplied waypoints cannot jump through an environmental box."""
    obstacle = box([0, 0, 0.2], [0.001, 0.05, 0.2])
    with TransitChecker(geometry, [obstacle], BOUNDS) as checker:
        assert checker.free([-1, 0, 0]) and checker.free([1, 0, 0])
        assert not checker.segment([-1, 0, 0], [1, 0, 0], resolution=2)


def test_base_route_calls_existing_prpl_mobile_planner(geometry, monkeypatch):
    """A real collision-checked route is generated by the shared BiRRT function."""
    calls = []
    original = urdf_collision.run_single_arm_mobile_base_motion_planning

    def tracked(*args, **kwargs):
        """Record reuse without replacing planning or collision decisions."""
        calls.append(True)
        return original(*args, **kwargs)

    monkeypatch.setattr(
        urdf_collision, "run_single_arm_mobile_base_motion_planning", tracked
    )
    obstacles = [box([-2, -2, 0.2], [0.1, 0.1, 0.2])]
    with TransitChecker(geometry, obstacles, BOUNDS) as checker:
        path = checker.route([0, 0, 0], [0.1, 0, 0.1])
        assert calls and len(path) >= 2
        assert np.allclose(path[0], [0, 0, 0]) and np.allclose(path[-1], [0.1, 0, 0.1])
    plan = {
        "required": True,
        "path_xyyaw": path,
        "radius_m": geometry["sweep_radius_m"],
        "transit_geometry": geometry,
        "bounds_xy": BOUNDS,
        "obstacles": obstacles,
    }
    validate_base_plan(plan)
    del plan["transit_geometry"]
    with pytest.raises(ValueError, match="Regenerate"):
        validate_base_plan(plan)


def test_model_posture_and_budget_are_bound_to_review(geometry):
    """Old robot-box reviews, altered assets and faster motion are rejected."""
    validate_model_geometry(geometry, MODEL, HOME, DEFAULT_NAVIGATION)
    for key, value in [
        ("schema", "model_boxes_v1"),
        ("urdf_sha256", "wrong"),
        ("sweep_radius_m", 0.1),
        ("joints_rad", [0] * 7),
    ]:
        bad = copy.deepcopy(geometry)
        bad[key] = value
        with pytest.raises(ValueError):
            validate_model_geometry(bad, MODEL, HOME, DEFAULT_NAVIGATION)
    with pytest.raises(ValueError, match="budget"):
        validate_model_geometry(
            geometry, MODEL, HOME, dict(DEFAULT_NAVIGATION, yaw_speed_rad_s=0.3)
        )


def test_urdf_tool_frame_matches_existing_render_and_live_model():
    """Catch mounting/tool/joint convention drift across preview and runtime."""
    kin = LiveKinematics(MODEL, [0.2, -0.1, 0.7], {"model_sha256": model_digest(MODEL)})
    with urdf_collision.PRPLCollisionScene() as scene:
        for q in (HOME, [0] * 7, [0.2, -0.4, 0.8, -1.5, 0.1, 0.6, -0.2]):
            scene.set([0.2, -0.1, 0.7], q)
            xyz, rotation = kin.full_pose(q)
            pose = scene.arm.get_end_effector_pose()
            assert np.allclose(pose.position, xyz, atol=2e-5)
            assert np.allclose(
                np.array(p.getMatrixFromQuaternion(pose.orientation)).reshape(3, 3),
                rotation,
                atol=2e-5,
            )


def test_real_ikfast_and_joint_planner_are_reused(monkeypatch):
    """Exercise genuine IK and BiRRT on a nearby reachable tool pose."""
    calls = []
    original = urdf_collision.run_motion_planning

    def tracked(*args, **kwargs):
        """Record reuse of the existing arm motion planner."""
        calls.append(True)
        return original(*args, **kwargs)

    monkeypatch.setattr(urdf_collision, "run_motion_planning", tracked)
    with urdf_collision.PRPLCollisionScene() as scene:
        scene.set([0, 0, 0], HOME)
        pose = scene.arm.get_end_effector_pose()
        rotation = np.array(p.getMatrixFromQuaternion(pose.orientation)).reshape(3, 3)
        goal = scene.solve(np.asarray(pose.position) + [0, 0, 0.005], rotation, HOME)
        path = scene.arm_path(HOME, goal, set())
        assert calls and len(path) >= 2
        assert np.allclose(path[0], HOME) and np.allclose(path[-1], goal)


def test_floor_is_arm_obstacle_but_support_for_base():
    """A wheeled base touching the ground must not block a raised-arm step."""
    with urdf_collision.PRPLCollisionScene() as scene:
        scene.set([0, 0, 0], HOME)
        floor = scene.box([0, 0, -0.1], [20, 20, 0.1])
        assert scene.collision({floor}, 0.005)
        assert not scene.collision({floor}, 0.005, arm_only=True)


def test_urdf_digest_is_identical_through_deployment_symlink(tmp_path, monkeypatch):
    """The linked deployment environment must hash exactly like the original."""
    assets = urdf_collision.get_assets_path()
    alias = tmp_path / "linked-environment-assets"
    alias.symlink_to(assets, target_is_directory=True)
    urdf_collision.urdf_digest.cache_clear()
    try:
        expected = urdf_collision.urdf_digest()
        monkeypatch.setattr(urdf_collision, "get_assets_path", lambda: alias)
        urdf_collision.urdf_digest.cache_clear()
        assert urdf_collision.urdf_digest() == expected
    finally:
        urdf_collision.urdf_digest.cache_clear()
